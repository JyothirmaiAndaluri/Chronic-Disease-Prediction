# 3. CLINICAL EXPLAINABILITY ENGINE (Logic preserved)
def get_clinical_explanation(data):
    X_input = pd.DataFrame([data])[list(X.columns)]
    shap_results = explainer.shap_values(X_input)
    if isinstance(shap_results, list):
        current_shap = shap_results[1][0]
    else:
        current_shap = shap_results[0, :, 1] if len(shap_results.shape) == 3 else shap_results[0]
    current_shap = np.array(current_shap).flatten()
    feature_names = list(X.columns)

    templates = {
        'SMOKING': 'Tobacco use is a primary driver of pulmonary risk.',
        'YELLOW_FINGERS': 'Staining associated with chronic nicotine exposure.',
        'ANXIETY': 'Psychological stress indicators observed.',
        'PEER_PRESSURE': 'Social environmental factors influencing habits.',
        'CHRONIC_DISEASE': 'Existing co-morbidities complicating lung health.',
        'FATIGUE': 'Persistent exhaustion is a systemic symptom of illness.',
        'ALLERGY': 'History of respiratory hypersensitivity.',
        'WHEEZING': 'Airway obstruction or respiratory distress noted.',
        'ALCOHOL_CONSUMING': 'Alcohol intake identified as a lifestyle risk factor.',
        'COUGHING': 'Persistent cough is a key indicator of lung distress.',
        'SHORTNESS_OF_BREATH': 'Dyspnea or difficulty breathing reported.',
        'SWALLOWING_DIFFICULTY': 'Dysphagia can indicate localized pressure/complications.',
        'CHEST_PAIN': 'Thoracic pain requiring clinical investigation.'
    }

    biological_symptoms = ['COUGHING', 'WHEEZING', 'CHEST_PAIN', 'SHORTNESS_OF_BREATH', 'SWALLOWING_DIFFICULTY', 'FATIGUE', 'YELLOW_FINGERS', 'CHRONIC_DISEASE', 'AGE']
    combined = []
    for name, val in zip(feature_names, current_shap):
        priority = 2 if name in biological_symptoms else 1
        combined.append((name, val, priority))

    impacts = sorted(combined, key=lambda x: (x[2], abs(x[1])), reverse=True)
    drivers, inhibitors = [], []

    for name, val, prio in impacts:
        if name == 'AGE':
            if val > 0.005: drivers.append(f"- Age: Patient age ({data['AGE']}) is a contributing risk factor.")
            elif val < -0.005: inhibitors.append(f"- Age: Patient age ({data['AGE']}) is currently a lower-risk factor.")
        elif name == 'GENDER':
            gender_label = 'Male' if data['GENDER'] == 1 else 'Female'
            if val > 0.005: drivers.append(f"- Gender: {gender_label} sex-based risk distribution.")
            elif val < -0.005: inhibitors.append(f"- Gender: {gender_label} sex-based risk distribution.")
        else:
            desc = templates.get(name, "Symptom impact detected.")
            if data.get(name) == 2 and val > 0.005:
                drivers.append(f"- {name.replace('_',' ').title()}: {desc}")
            elif data.get(name) == 1 and val < -0.005:
                inhibitors.append(f"- {name.replace('_',' ').title()}: No symptoms reported.")
    return drivers, inhibitors

def get_risk_assessment(prob_pct):
    if prob_pct < 30: return "LOW"
    elif prob_pct < 55: return "MODERATE"
    elif prob_pct < 75: return "HIGH"
    else: return "VERY HIGH"

# 4. EXECUTION
def take_input():
    print("\n" + "="*40 + "\n   LUNG CANCER RISK ASSESSMENT\n" + "="*40)
    data = {'GENDER': 1 if input("Gender (M/F): ").strip().upper() == "M" else 0, 'AGE': int(input("Age: "))}
    symptoms = ['SMOKING','YELLOW_FINGERS','ANXIETY','PEER_PRESSURE','CHRONIC_DISEASE','FATIGUE','ALLERGY','WHEEZING','ALCOHOL_CONSUMING','COUGHING','SHORTNESS_OF_BREATH','SWALLOWING_DIFFICULTY','CHEST_PAIN']
    print("\nEnter Symptoms (Y/N):")
    for s in symptoms:
        data[s] = 2 if input(f" > {s.replace('_',' ').title()}: ").strip().upper() == "Y" else 1
    return data

user_data = take_input()
prob_pct = round(float(model.predict_proba(pd.DataFrame([user_data])[list(X.columns)])[0, 1]) * 100, 1)
drivers, inhibitors = get_clinical_explanation(user_data)

print("\n" + "*"*45 + "\n           OFFICIAL CLINICAL REPORT\n" + "*"*45)
print(f"DIAGNOSTIC PROBABILITY: {prob_pct}%")
print(f"RISK LEVEL:             {get_risk_assessment(prob_pct)}")
print("\n--- CLINICAL DETAILS ---\nRISK FACTORS DETECTED (Prioritized):")
for line in drivers[:5]: print(line)
print("\nPROTECTIVE OBSERVATIONS:")
for line in inhibitors[:3]: print(line)
